type Value = {
  locale: Locale;
  isRTL: boolean;
  t: (key: string) => string;
  toggleLocale: () => void;
};

const C = createContext<Value | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("ar");

  useEffect(() => {
    AsyncStorage.getItem("e3lani.locale")
      .then((value) => {
        if (value === "ar" || value === "en") setLocale(value);
      })
      .catch(() => undefined);
  }, []);

  useEffect(() => {
    const rtl = locale === "ar";
    I18nManager.allowRTL(true);
    if (Platform.OS === "web" && typeof document !== "undefined") {
      document.documentElement.dir = rtl ? "rtl" : "ltr";
      document.documentElement.lang = locale;
    }
  }, [locale]);

  const value = useMemo<Value>(
    () => ({
      locale,
      isRTL: locale === "ar",
      t: (key) => (locale === "ar" ? ar[key] : en[key]) ?? key,
      toggleLocale: () =>
        setLocale((current) => {
          const next = current === "ar" ? "en" : "ar";
          AsyncStorage.setItem("e3lani.locale", next).catch(() => undefined);
          return next;
        }),
    }),
    [locale],
  );

  return <C.Provider value={value}>{children}</C.Provider>;
}

export function useI18n() {
  const value = useContext(C);
  if (!value) throw new Error("I18nProvider missing");
  return value;
}
